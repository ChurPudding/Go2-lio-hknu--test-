#!/usr/bin/env python3
"""
go2_calib.py -- Go2 + L1 외부 파라미터 공용 상수

l1_imu_fix.py, robot_pose.py 가 이 모듈을 import 한다 (goto_node.py 는 미작성).
값을 고칠 일이 있으면 반드시 여기만 고칠 것. 노드마다 복사해 두면
한 곳을 놓쳐 조용히 틀린 결과가 나온다.

    from go2_calib import R_LB, R_BL, LEVER, FWD_L, ACC_SCALE_BODY

추정 근거는 go2_l1_imu_진단정리.md 3.5절 / 4절 참조.
"""
import numpy as np

# ---------------------------------------------------------------
# 회전: base_link -> L1/LiDAR 프레임
#   /utlidar/imu 자이로와 /lowstate 자이로의 각속도 벡터를 Kabsch 정렬.
#   두 IMU 의 내부 필터 대역이 달라 위상이 어긋나므로 양쪽을 2Hz
#   저역통과로 맞춘 뒤 정렬 (설명력 98.0%, 시간지연 -6ms 보정).
#   독립 시간창 7개에서 yaw 성분 -126.9 ~ -128.4deg 로 일치 -> 확정.
#   중력방향 교차검증 1.24deg.
# ---------------------------------------------------------------
R_LB = np.array([
    [+0.523029, -0.838576, +0.152420],
    [-0.810712, -0.544668, -0.214668],
    [+0.263034, -0.011292, -0.964721],
])

R_BL = R_LB.T                                  # LiDAR -> base_link

# 로봇 정면(base_link +x)을 LiDAR 프레임으로 표현한 벡터.
# 이걸 쓰지 않고 오도메트리 자세를 그대로 heading 으로 쓰면 약 128deg 틀어진다.
FWD_L = R_LB @ np.array([1.0, 0.0, 0.0])

# ---------------------------------------------------------------
# 평행이동: base_link 원점 -> LiDAR 원점, base_link 프레임 표현 [m]
#   x,y : 8초 창 13개에 창별 정렬을 따로 두고 r 을 공유해 최소자승 추정.
#         잔차 0.238 -> 0.143 m (40% 개선). 방향 +0.9deg = 거의 정면.
#   z   : 관측 불가 (몸통 roll/pitch 변화 부족으로 평행이동 항과 상쇄).
#         지면까지 거리 0.355~0.364 m 와 몸통 높이 0.308 m 에서 역산한 근사값.
#         정밀도가 필요하면 실측할 것.
# ---------------------------------------------------------------
LEVER = np.array([0.322, 0.005, 0.050])

# ---------------------------------------------------------------
# 본체 가속도계 스케일 보정
#   /lowstate 가속도계 정지 |a| = 9.465 m/s^2 (표준중력 9.807 대비 -3.49%)
# ---------------------------------------------------------------
ACC_REST_BODY = 9.465
ACC_SCALE_BODY = 9.807 / ACC_REST_BODY         # = 1.03614

# 참고 (사용하지 않음): L1 가속도계 정지 |a| = 10.437 (+6.4%).
# 단 이 데이터는 실제 로봇 가속도와 상관 <=0.19 로 사용 불가.

# ---------------------------------------------------------------
# 검증용 기대값
#   정지 상태에서 /l1_imu_fixed 의 linear_acceleration
# ---------------------------------------------------------------
EXPECTED_REST_ACC = R_LB @ (np.array([-0.0091, -0.0256, 0.9996]) * 9.807)
# ~= (+1.66, -1.90, -9.48).  실측 (1.56, -1.81, -9.51)


if __name__ == '__main__':
    np.set_printoptions(precision=6, suppress=True)
    print('R_LB (base_link -> LiDAR) =\n', R_LB)
    print('det =', np.linalg.det(R_LB))
    print('FWD_L =', FWD_L)
    print('LEVER =', LEVER)
    print('ACC_SCALE_BODY = %.5f' % ACC_SCALE_BODY)
    print('정지 시 /l1_imu_fixed 기대 가속도 =', EXPECTED_REST_ACC)


